def save(fig,name):
    fig.tight_layout()
    metadata={'Description':'Original scientific plot; source: scripts/plot_noise.py; archived GF180 .noise or labeled analytic formula.'}
    fig.savefig(OUT/(name+'.svg'),metadata={'Date':None,**metadata})
    p=OUT/(name+'.svg');p.write_text('\n'.join(x.rstrip() for x in p.read_text(encoding='utf-8').splitlines())+'\n',encoding='utf-8',newline='\n')
    origin='Origin: original scientific plot, generated by scripts/plot_noise.py from archived GF180 ngspice PSD or explicitly labeled analytic formulas. Not generative imagery.'
    fig.savefig(OUT/(name+'.png'),dpi=180,metadata={**metadata,'impeccable:prompt':origin});plt.close(fig)


def statistics():
    """Finite random-phase samples: periodogram area equals record variance.

    This is an analytic statistics example, never a SPICE noise transient.
    No Gaussian amplitude distribution is asserted by the spectrum.
    """
    n=8192;fs=8192;rng=np.random.default_rng(71)
    f=np.fft.rfftfreq(n,1/fs);time=np.arange(n)/fs
    fig,axs=plt.subplots(3,1,figsize=(4.4,6.8))
    for column,(lo,hi,color,label) in enumerate([(1,32,TEAL,'A: 1-32 Hz'),(256,1024,BLUE,'B: 256-1024 Hz')]):
        bins=(f>=lo)&(f<=hi);z=np.zeros(len(f),complex)
        z[bins]=np.exp(1j*rng.uniform(0,2*np.pi,bins.sum()))
        x=np.fft.irfft(z,n);x=x/np.sqrt(np.mean(x*x))*10
        psd=2*np.abs(np.fft.rfft(x))**2/(fs*n);psd[[0,-1]]/=2
        # The uniform frequency grid and Parseval give an exact finite-record check.
        assert abs(psd.sum()*(fs/n)-np.mean(x*x))<1e-10
        assert abs(np.sqrt(np.mean(x*x))-10)<1e-12
        axs[column].plot(time[:1024]*1000,x[:1024],color=color,lw=1.1)
        axs[column].set_title(label+' · 10 µV RMS',color=color,loc='left',fontsize=12)
        axs[column].set(xlabel='Time (ms)',ylabel='Sample (µV)',xlim=(0,125),ylim=(-35,35))
        # Plot complete periodogram values on a linear frequency axis: area is variance.
        axs[2].plot(f,psd,color=color,lw=1.3,label=label)
        axs[2].fill_between(f,psd,color=color,alpha=.12)
        axs[2].set(xlabel='Frequency (Hz)',ylabel='PSD estimate\n(µV²/Hz)',xlim=(0,1200),ylim=(0,3.5))
    axs[2].text(.95,.86,'Both areas = 100 µV²',transform=axs[2].transAxes,ha='right',fontsize=10)
    axs[2].legend(loc='center right',frameon=False,fontsize=10)
    for ax in axs.flat:ax.spines[['top','right']].set_visible(False);ax.grid(alpha=.15)
    save(fig,'noise-statistics')


def main():
    # Evidence role: how physical mechanism and sizing change an actual input PSD.
    fig,ax=plt.subplots(figsize=(7.2,4.8))
    for name,label,color in [('baseline','GF180 baseline',INK),('area-budget','GF180 area candidate',TEAL)]:
        a=np.loadtxt(LAB/(name+'-spectrum.csv'),delimiter=',',skiprows=1);a=a[a[:,0]<=1e6]
        f=a[:,0];ax.loglog(f,np.sqrt(a[:,2])*1e9,color=color,lw=2,label=label)
        if name=='baseline':
            fl=a[:,16:22].sum(axis=1)*a[:,2]/a[:,1]
            ax.loglog(f,np.sqrt(fl)*1e9,color=AMBER,ls='--',label='Baseline: model flicker')
            ax.loglog(f,np.sqrt(a[:,2]-fl)*1e9,color=BLUE,ls=':',lw=2,label='Baseline: non-flicker')
    ax.axvspan(100,1e5,color=BLUE,alpha=.055);ax.set(xlabel='Frequency (Hz)',ylabel='Input-referred ASD (nV / sqrt(Hz))',xlim=(1,1e6))
    ax.grid(alpha=.16,which='major');ax.legend();save(fig,'noise-spectrum')
    # Evidence role: fractions must be variance fractions, never RMS sums.
    m=json.loads((LAB/'metrics.json').read_text(encoding='utf-8'))['baseline']['bands'][1]
    labels=['Input pair M1 + M2','PMOS mirror M3 + M4','Tail Mt','Reference Mr + Rref']
    vals=np.array(list(m['source_input_variance_V2'].values()));shares=vals/vals.sum()*100
    fig,ax=plt.subplots(figsize=(7.2,3.6));bars=ax.barh(np.arange(4),shares,color=[TEAL,BLUE,AMBER,'#6a7f8e'],height=.52)
    ax.set_yticks(range(4),labels);ax.invert_yaxis();ax.set(xlabel='Fraction of input noise variance (%)',xlim=(0,105))
    for bar,v in zip(bars,shares):ax.text(v+1,bar.get_y()+bar.get_height()/2,f'{v:.3f}%' if v<1 else f'{v:.1f}%',va='center',color=INK)
    ax.spines[['top','right']].set_visible(False);ax.grid(axis='x',alpha=.16);ax.set_axisbelow(True);save(fig,'noise-budget')
    # Evidence role: a log-axis shaded ASD is NOT noise power. Correct Jacobian.
    f=np.logspace(0,6,601);p=1e-16*(1+1000/f);selected=(f>=100)&(f<=1e5)
    fig,axs=plt.subplots(2,1,figsize=(7.2,6.3),sharex=True)
    axs[0].loglog(f,np.sqrt(p)*1e9,color=INK,lw=2);axs[0].set_ylabel('ASD (nV / sqrt(Hz))')
    density=np.log(10)*f*p*1e12;axs[1].semilogx(f,density,color=BLUE,lw=2)
    axs[1].fill_between(f,0,density,where=selected,color=BLUE,alpha=.22);axs[1].set(xlabel='Frequency (Hz)',ylabel='Variance per decade (uV² / dec)',ylim=(0,250))
    for ax in axs:ax.axvspan(100,1e5,color=BLUE,alpha=.05);ax.grid(alpha=.16);ax.set_xlim(1,1e6)
    axs[0].text(.97,.9,'Analytic: 10 nV/sqrt(Hz), fc = 1 kHz',transform=axs[0].transAxes,ha='right',fontsize=10)
    axs[1].text(.04,.86,'100 Hz - 100 kHz: 3.27 uV RMS',transform=axs[1].transAxes,fontsize=11,color=INK)
    save(fig,'noise-band')


if __name__=='__main__':statistics();main()
